export function useI18n() {
  const [locale, setLocale] = useState<Locale>(() => (localStorage.getItem('lan-locale') as Locale) || 'zh');
  useEffect(() => {
    localStorage.setItem('lan-locale', locale);
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
  }, [locale]);
  const t = useCallback((key: string) => (locale === 'zh' ? zh[key] || key : en[key] || key), [locale]);
  return { locale, setLocale, t };
}
